-- Writes the settings class of a module for the game's own options (ModKit: UGothicModExt_UserSettings) from the
-- module's schema.lua of the UE4SS mod - one description of every setting, as before.
--
--   lua5.4 modkit/tools/gen_settings.lua <module> [--check]       (from the repository's root)
--
-- Kinds: bool -> FModUserSettingsBool; number -> FModUserSettingsInt (no decimals) or FModUserSettingsFloat;
-- choice -> FModUserSettingsInt 1..n (the options in its text); key -> FModUserSettingsInt (a key number, Keys.as);
-- text -> a plain config string (not in the options menu: GameUserSettings.ini only); action and hidden: none.
-- Settings that cannot work from the game's scripts are left out (NOT_IN_GAME, with the reason).
local ROOT = (arg[0]:match("^(.*)/modkit/tools/[^/]*$") or ".") .. "/"
local module, check = arg[1], arg[2] == "--check"
if not module then io.stderr:write("usage: lua5.4 modkit/tools/gen_settings.lua <module> [--check]\n") os.exit(2) end
local schema = dofile(module == "markers" and (ROOT .. "app/src/MapPinsSchema.lua")
    or (ROOT .. "G1R_MegaMod/modules/" .. module .. "/Scripts/schema.lua"))

-- module -> key -> why it is not in the game's options
local NOT_IN_GAME = {
    intro = { SkipLogos = "the logos play before any script runs: the settings app writes the line into Game.ini" },
}

local function camel(s) return (s:gsub("^%l", string.upper)) end
local CLASS = "UMegaSettings_" .. camel(module)
local function str(s) return '"' .. tostring(s):gsub("\\", "\\\\"):gsub('"', '\\"') .. '"' end
local function num(v, decimals)
    if decimals and decimals > 0 then
        local s = string.format("%." .. decimals .. "f", v):gsub("0+$", ""):gsub("%.$", ".0")
        return s .. "f"
    end
    return string.format("%d", math.floor(v + 0.5))
end
local function label(item)
    local l = item.MenuLabel or item.Label or item.Key
    if not item.MenuLabel and item.Unit and #l + #item.Unit + 3 <= 48 then l = l .. " (" .. item.Unit .. ")" end
    return l
end

local out = {}
local function w(s) out[#out + 1] = s end
w("// Generated by modkit/tools/gen_settings.lua from G1R_MegaMod/modules/" .. module .. "/Scripts/schema.lua - do not edit.")
w("// This is an unofficial modification. It is not made, endorsed or supported by THQ Nordic.")
w("")
w("UCLASS(Config=GameUserSettings)")
w("class " .. CLASS .. " : UGothicModExt_UserSettings")
w("{")
w("\tdefault CategoryName = FText::FromString(" .. str("MegaMod: " .. tostring(schema.Page or module)) .. ");")
for _, group in ipairs(schema.Groups) do
    local first = true
    for _, item in ipairs(group.Items) do
        local away = NOT_IN_GAME[module] and NOT_IN_GAME[module][item.Key]
        if away then
            if first then w("") w("\t// ---- " .. tostring(group.Title) .. " ----") first = false end
            w("")
            w("\t// " .. item.Key .. ": not here - " .. away)
        elseif not item.Hidden and item.Kind ~= "action" then
            if first then w("") w("\t// ---- " .. tostring(group.Title) .. " ----") first = false end
            local k = item.Kind
            w("")
            if k == "bool" then
                w("\tUPROPERTY(Config)")
                w("\tFModUserSettingsBool " .. item.Key .. " = FModUserSettingsBool(")
                w("\t\tValue = " .. tostring(item.Default) .. ",")
                w("\t\tDefaultValue = " .. tostring(item.Default) .. ",")
                w("\t\tDisplayText = FText::FromString(" .. str(label(item)) .. "));")
            elseif k == "number" and (item.Decimals or 0) > 0 then
                w("\tUPROPERTY(Config)")
                w("\tFModUserSettingsFloat " .. item.Key .. " = FModUserSettingsFloat(")
                w("\t\tValue = " .. num(item.Default, item.Decimals) .. ",")
                w("\t\tDefaultValue = " .. num(item.Default, item.Decimals) .. ",")
                w("\t\tDisplayText = FText::FromString(" .. str(label(item)) .. "),")
                w("\t\tMinValue = " .. num(item.Min, item.Decimals) .. ",")
                w("\t\tMaxValue = " .. num(item.Max, item.Decimals) .. ",")
                w("\t\tStepSize = " .. num(item.Step or 1, item.Decimals) .. ");")
            elseif k == "number" then
                w("\tUPROPERTY(Config)")
                w("\tFModUserSettingsInt " .. item.Key .. " = FModUserSettingsInt(")
                w("\t\tValue = " .. num(item.Default) .. ",")
                w("\t\tDefaultValue = " .. num(item.Default) .. ",")
                w("\t\tDisplayText = FText::FromString(" .. str(label(item)) .. "),")
                w("\t\tMinValue = " .. num(item.Min) .. ",")
                w("\t\tMaxValue = " .. num(item.Max) .. ");")
            elseif k == "choice" then
                local index, names = 1, {}
                for i, o in ipairs(item.Options) do
                    names[#names + 1] = i .. " " .. o
                    if o == item.Default then index = i end
                end
                w("\t// " .. table.concat(names, ", "))
                w("\tUPROPERTY(Config)")
                w("\tFModUserSettingsInt " .. item.Key .. " = FModUserSettingsInt(")
                w("\t\tValue = " .. index .. ",")
                w("\t\tDefaultValue = " .. index .. ",")
                w("\t\tDisplayText = FText::FromString(" .. str(label(item) .. ": " .. table.concat(names, ", ")) .. "),")
                w("\t\tMinValue = 1,")
                w("\t\tMaxValue = " .. #item.Options .. ");")
            elseif k == "key" then
                w("\t// a key number of Keys.as (0 = no key)")
                w("\tUPROPERTY(Config)")
                w("\tFModUserSettingsInt " .. item.Key .. " = FModUserSettingsInt(")
                w("\t\tValue = 0,")
                w("\t\tDefaultValue = 0,")
                w("\t\tDisplayText = FText::FromString(" .. str(label(item) .. " (key number, 0 = none)") .. "),")
                w("\t\tMinValue = 0,")
                w("\t\tMaxValue = 58);")
            elseif k == "text" then
                w("\t// not in the options menu: GameUserSettings.ini only")
                w("\tUPROPERTY(Config)")
                w("\tFString " .. item.Key .. " = " .. str(item.Default or "") .. ";")
            end
        end
    end
end
w("}")
local text = table.concat(out, "\n") .. "\n"
local path = ROOT .. "modkit/G1R_MegaMod/Script/G1R_MegaMod/Settings/" .. camel(module) .. "Settings.as"
if check then
    local f = io.open(path, "rb")
    local have = f and f:read("a") or nil
    if f then f:close() end
    if have ~= text then print("differs: " .. path) os.exit(1) end
    print("same: " .. path)
else
    os.execute('mkdir -p "' .. ROOT .. 'modkit/G1R_MegaMod/Script/G1R_MegaMod/Settings"')
    local f = assert(io.open(path, "wb"))
    f:write(text)
    f:close()
    print("written: " .. path)
end
