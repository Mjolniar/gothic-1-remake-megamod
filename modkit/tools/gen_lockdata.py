"""Writes modkit/G1R_MegaMod/Script/G1R_MegaMod/Locks/MegaLockData.as from the locks module's lockdata.lua.

    python3 modkit/tools/gen_lockdata.py            write the file
    python3 modkit/tools/gen_lockdata.py --check    exit 1 when the file is not what lockdata.lua gives
"""
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SOURCE = os.path.join(ROOT, "G1R_MegaMod", "modules", "locks", "Scripts", "lockdata.lua")
TARGET = os.path.join(ROOT, "modkit", "G1R_MegaMod", "Script", "G1R_MegaMod", "Locks", "MegaLockData.as")


def build():
    rows = re.findall(r'\["([A-Za-z0-9_]+)"\] = \{ (\d+), (\d+) \}', open(SOURCE, encoding="utf-8").read())
    if len(rows) < 100:
        sys.exit("lockdata.lua: only %d rows found" % len(rows))
    lines = [
        "// Generated by modkit/tools/gen_lockdata.py from G1R_MegaMod/modules/locks/Scripts/lockdata.lua - do not edit.",
        "// This is an unofficial modification. It is not made, endorsed or supported by THQ Nordic.",
        "//",
        "// Per lock: the number of its connections, and how many of them can be taken away with the lock proven to stay",
        "// solvable (made with a solver from the game's lock definitions; see the locks module's facts file).",
        "",
        "class UMegaLockData : UScriptGameInstanceSubsystem",
        "{",
        "\tTMap<FName, int> Connections;",
        "\tTMap<FName, int> Proven;",
        "",
        "\t// false for a lock that is not in the table",
        "\tbool Find(FName Lock, int& OutConnections, int& OutProven)",
        "\t{",
        "\t\tif (Connections.Num() == 0)",
        "\t\t\tFill();",
        "\t\tif (!Connections.Contains(Lock))",
        "\t\t\treturn false;",
        "\t\tOutConnections = Connections[Lock];",
        "\t\tOutProven = Proven[Lock];",
        "\t\treturn true;",
        "\t}",
        "",
        "\tvoid Put(FName Lock, int Count, int Safe)",
        "\t{",
        "\t\tConnections.Add(Lock, Count);",
        "\t\tProven.Add(Lock, Safe);",
        "\t}",
        "",
        "\tvoid Fill()",
        "\t{",
    ]
    lines += ['\t\tPut(n"%s", %s, %s);' % r for r in rows]
    lines += ["\t}", "}", ""]
    return "\n".join(lines)


def main():
    text = build()
    if "--check" in sys.argv:
        old = open(TARGET, encoding="utf-8").read() if os.path.isfile(TARGET) else ""
        if old != text:
            print("MegaLockData.as is not up to date: run modkit/tools/gen_lockdata.py")
            return 1
        print("MegaLockData.as up to date")
        return 0
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote " + TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main())
