"""Writes Script/G1R_MegaMod/Repopulate/MegaRegrowth.as: the herb and loose-item spawners of the main map with the
refill times of the settings (UMegaSettings_Repopulate HerbHours / ItemHours, read when the game starts).

    python3 modkit/tools/gen_regrowth.py <G1R-Modkit/Script>

The spawners' item lists come from the game's own ItemSpawnManagerConfig_MainMap.as of the official ModKit (a ModKit
spawner given again replaces the game's entry of that name, so it is given with all its lines). Which spawners: the
"herb" and "loose" points of the repopulate data (G1R_MegaMod/modules/repopulate/Scripts/data/item_points.lua;
quest, unique, key, map and writing items are not in it). The output holds the game's item lists, so it is not kept in
this public repository (.gitignore): it is made on the PC that builds the package.
"""
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
POINTS = os.path.join(ROOT, "G1R_MegaMod", "modules", "repopulate", "Scripts", "data", "item_points.lua")
TARGET = os.path.join(ROOT, "modkit", "G1R_MegaMod", "Script", "G1R_MegaMod", "Repopulate", "MegaRegrowth.as")
KEEP = ("AddItemsEvent", "AddItem", "AddOwnerCharacter", "AddOwnerGuild", "SetInheritOwnershipFromArea")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    config = os.path.join(sys.argv[1], "Map", "MainMap", "ItemSpawnManagerConfig_MainMap.as")
    kinds = dict(re.findall(r'\["([^"]+)"\] = \{ p = "(herb|loose)"', open(POINTS, encoding="utf-8").read()))
    blocks, name, lines, refill = [], None, [], 0
    for raw in open(config, encoding="utf-8"):
        line = raw.strip()
        m = re.match(r'default SetWorldPoint\(n"([^"]+)"\);$', line)
        if m:
            if name:
                blocks.append((name, refill, lines))
            name, lines, refill = m.group(1), [], 0
            continue
        m = re.match(r"default SetRefill\((\d+)\);$", line)
        if m and name:
            refill = int(m.group(1))
            continue
        m = re.match(r"default (\w+)\((.*)\);$", line)
        if m and name and m.group(1) in KEEP:
            lines.append("%s(%s)" % (m.group(1), m.group(2)))
    if name:
        blocks.append((name, refill, lines))
    out = [
        "// Generated by modkit/tools/gen_regrowth.py from the ModKit's ItemSpawnManagerConfig_MainMap.as - do not edit,",
        "// not in the repository (it holds the game's item lists).",
        "// This is an unofficial modification. It is not made, endorsed or supported by THQ Nordic.",
        "",
        "class UGothicModExt_MegaRegrowth : UGothicModExt_WorldPoints",
        "{",
        "\tdefault ItemSpawnConfigToExtend = UItemSpawnManagerConfig_MainMap;",
        "\tdefault WorldPointManagerConfigToExtend = UWorldpointManagerConfig_MainMap;",
    ]
    count = {"herb": 0, "loose": 0}
    for name, refill, lines in blocks:
        kind = kinds.get(name)
        if not kind or not lines:
            continue
        count[kind] += 1
        out.append("")
        out.append('\tdefault Items.SetWorldPoint(n"%s");' % name)
        hours = "MegaRegrowth::Herb(%d)" % refill if kind == "herb" else "MegaRegrowth::Loose()"
        out.append("\tdefault Items.SetRefill(%s);" % hours)
        for l in lines:
            out.append("\tdefault Items.%s;" % l)
    out += ["}", ""]
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote %s: %d herb and %d loose-item spawners (%d points in the data)" % (TARGET, count["herb"], count["loose"], len(kinds)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
